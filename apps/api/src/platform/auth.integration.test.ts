import test from "node:test";
import assert from "node:assert/strict";
import {randomBytes,randomUUID} from "node:crypto";
import {MongoClient} from "mongodb";
import Fastify from "fastify";
import {provisionTenant,setTenantStatus,createUser,createMembership,runCoreMigrations} from "@zuri/core-platform";
import {issueInvitation,acceptInvitation,login,beginMfaEnrollment,confirmMfaEnrollment,verifyMfaLogin,disableMfa,refreshLogin,issuePasswordReset,resetPassword,logout,listUserWorkspaces,selectWorkspace,switchWorkspace} from "./auth-service.js";
import {totpCode} from "./auth-crypto.js";
import {authRoutes} from "./auth-routes.js";
const uri=process.env.MONGODB_TEST_URI;
test("invitation acceptance and password login use active tenant membership", {skip:!uri}, async()=>{
 const client=new MongoClient(uri!);await client.connect();
 const db=client.db("zuri_auth_"+randomUUID().replaceAll("-",""));
 try{
  await runCoreMigrations(db);
  await db.collection("auth_rate_limits").createIndex({key:1},{unique:true});
  await db.collection("auth_challenges").createIndex({challengeId:1},{unique:true});
  const tenant=await provisionTenant(db,"test",{slug:"auth-test",legalName:"Auth Test Ltd",displayName:"Auth Test"});
  await setTenantStatus(db,tenant.tenantId,"active","test");
  const user=await createUser(db,"test",{email:"auth@example.test",displayName:"Auth User"});
  const invitation=await issueInvitation(db,user.userId);
  const password=randomBytes(24).toString("base64url");
  await acceptInvitation(db,user.userId,invitation,password);
  await createMembership(db,tenant.tenantId,"test",{userId:user.userId});
  const secondTenant=await provisionTenant(db,"test",{slug:"auth-test-two",legalName:"Auth Test Two Ltd",displayName:"Auth Test Two"});
  await setTenantStatus(db,secondTenant.tenantId,"active","test");
  await createMembership(db,secondTenant.tenantId,"test",{userId:user.userId});

  const cfg={issuer:"https://identity.example.test",audience:"zuri-api-test",jwtSecret:randomBytes(32).toString("base64url"),accessTokenTtlSeconds:900,sessionTtlSeconds:3600,mfaEncryptionKey:randomBytes(32).toString("base64")};
  const workspaceLogin=await login(db,cfg,{email:"AUTH@example.test",password,ipHash:"multi-workspace"});
  assert.equal(workspaceLogin.mfaRequired,false);
  if(!("selectionToken" in workspaceLogin))throw new Error("Expected workspace selection after identity authentication");
  assert.equal(workspaceLogin.workspaces.length,2);
  assert.deepEqual(new Set(workspaceLogin.workspaces.map(w=>w.tenantId)),new Set([tenant.tenantId,secondTenant.tenantId]));
  const selected=await selectWorkspace(db,cfg,workspaceLogin.selectionToken,secondTenant.tenantId);
  assert.ok(selected.accessToken);
  await assert.rejects(()=>selectWorkspace(db,cfg,workspaceLogin.selectionToken,tenant.tenantId));
  const choices=await listUserWorkspaces(db,user.userId);
  assert.equal(choices.length,2);
  const orphan=await createUser(db,"test",{email:"orphan@example.test",displayName:"No Workspace User"});
  const orphanPassword=randomBytes(24).toString("base64url"),orphanInvitation=await issueInvitation(db,orphan.userId);
  await acceptInvitation(db,orphan.userId,orphanInvitation,orphanPassword);
  const orphanLogin=await login(db,cfg,{email:"orphan@example.test",password:orphanPassword,ipHash:"orphan"});
  assert.equal(orphanLogin.mfaRequired,false);
  if(!("selectionToken" in orphanLogin))throw new Error("Expected workspace selection for an account without memberships");
  assert.equal(orphanLogin.workspaces.length,0);
  await assert.rejects(()=>selectWorkspace(db,cfg,orphanLogin.selectionToken,tenant.tenantId));
  const switched=await switchWorkspace(db,cfg,{userId:user.userId,tenantId:secondTenant.tenantId,sessionId:selected.sessionId,targetTenantId:tenant.tenantId});
  assert.ok(switched.accessToken);
  const priorContext=await db.collection("sessions").findOne({tenantId:secondTenant.tenantId,sessionId:selected.sessionId});
  assert.ok(priorContext?.revokedAt);
  const result=await login(db,cfg,{email:"AUTH@example.test",password,tenantSlug:tenant.slug,ipHash:"integration"});
  assert.equal(result.mfaRequired,false);
  if(result.mfaRequired)throw new Error("Unexpected MFA challenge");
  assert.ok(result.accessToken);
  const refreshed=await refreshLogin(db,cfg,tenant.tenantId,result.sessionId,result.refreshToken);
  assert.ok(refreshed.accessToken);assert.ok(refreshed.refreshToken);

  const enrollment=await beginMfaEnrollment(db,user.userId,cfg);
  const recovery=await confirmMfaEnrollment(db,user.userId,totpCode(enrollment.secret),cfg);
  assert.equal(recovery.recoveryCodes.length,10);
  const identityMfa=await login(db,cfg,{email:"auth@example.test",password,ipHash:"identity-mfa"});
  if(!identityMfa.mfaRequired)throw new Error("Expected identity-level MFA challenge");
  const postMfaSelection=await verifyMfaLogin(db,cfg,identityMfa.challengeToken,recovery.recoveryCodes[2]!);
  if(!("selectionToken" in postMfaSelection))throw new Error("MFA must complete before workspace selection");
  assert.equal(postMfaSelection.workspaces.length,2);
  const postMfaSession=await selectWorkspace(db,cfg,postMfaSelection.selectionToken,tenant.tenantId);
  assert.ok(postMfaSession.accessToken);
  await logout(db,tenant.tenantId,postMfaSession.sessionId,user.userId);
  const mfaAttempt=await login(db,cfg,{email:"auth@example.test",password,tenantSlug:tenant.slug,ipHash:"integration"});
  if(!mfaAttempt.mfaRequired)throw new Error("Expected MFA challenge");
  const second=await verifyMfaLogin(db,cfg,mfaAttempt.challengeToken,recovery.recoveryCodes[0]!);
  assert.ok(second.accessToken);
  await assert.rejects(()=>verifyMfaLogin(db,cfg,mfaAttempt.challengeToken,recovery.recoveryCodes[0]!));

  const totpAttempt=await login(db,cfg,{email:"auth@example.test",password,tenantSlug:tenant.slug,ipHash:"integration"});
  if(!totpAttempt.mfaRequired)throw new Error("Expected MFA challenge");
  const futureStep=Math.floor(Date.now()/30_000)+1;
  const third=await verifyMfaLogin(db,cfg,totpAttempt.challengeToken,totpCode(enrollment.secret,futureStep));
  assert.ok(third.accessToken);
  await disableMfa(db,user.userId,password,recovery.recoveryCodes[1]!,cfg);

  const reset=await issuePasswordReset(db,"auth@example.test");
  assert.ok(reset);
  const newPassword=randomBytes(24).toString("base64url");
  await resetPassword(db,user.userId,reset!.token,newPassword);
  const oldSession=await db.collection("sessions").findOne({tenantId:tenant.tenantId,sessionId:third.sessionId});
  assert.ok(oldSession?.revokedAt);
  const afterReset=await login(db,cfg,{email:"auth@example.test",password:newPassword,tenantSlug:tenant.slug,ipHash:"integration"});
  assert.equal(afterReset.mfaRequired,false);
  if(afterReset.mfaRequired)throw new Error("MFA should be disabled");
  await logout(db,tenant.tenantId,afterReset.sessionId,user.userId);
  const loggedOut=await db.collection("sessions").findOne({tenantId:tenant.tenantId,sessionId:afterReset.sessionId});
  assert.ok(loggedOut?.revokedAt);

  const app=Fastify();
  await app.register(authRoutes(db,cfg));
  const routeLogin=await app.inject({method:"POST",url:"/auth/login",payload:{email:"auth@example.test",password:newPassword}});
  assert.equal(routeLogin.statusCode,200);
  const routeLoginBody=routeLogin.json() as {workspaceSelectionRequired:boolean;selectionToken:string;workspaces:Array<{tenantId:string}>};
  assert.equal(routeLoginBody.workspaceSelectionRequired,true);
  assert.equal(routeLoginBody.workspaces.length,2);
  const routeSelect=await app.inject({method:"POST",url:"/auth/workspace/select",payload:{selectionToken:routeLoginBody.selectionToken,tenantId:tenant.tenantId}});
  assert.equal(routeSelect.statusCode,200);
  const routeBody=routeSelect.json() as {accessToken:string;sessionId:string};
  const routeWorkspaces=await app.inject({method:"GET",url:"/auth/workspaces",headers:{authorization:"Bearer "+routeBody.accessToken}});
  assert.equal(routeWorkspaces.statusCode,200);
  assert.equal(routeWorkspaces.json().workspaces.length,2);
  const routeSwitch=await app.inject({method:"POST",url:"/auth/workspace/switch",headers:{authorization:"Bearer "+routeBody.accessToken},payload:{tenantId:secondTenant.tenantId}});
  assert.equal(routeSwitch.statusCode,200);
  const switchedRouteSession=routeSwitch.json() as {accessToken:string;sessionId:string};
  const me=await app.inject({method:"GET",url:"/auth/me",headers:{authorization:"Bearer "+switchedRouteSession.accessToken}});
  assert.equal(me.statusCode,200);
  assert.equal(me.json().principal.userId,user.userId);
  assert.equal(me.json().principal.tenantId,secondTenant.tenantId);
  const routeLogout=await app.inject({method:"POST",url:"/auth/logout",headers:{authorization:"Bearer "+switchedRouteSession.accessToken}});
  assert.equal(routeLogout.statusCode,204);
  const meAfterLogout=await app.inject({method:"GET",url:"/auth/me",headers:{authorization:"Bearer "+switchedRouteSession.accessToken}});
  assert.equal(meAfterLogout.statusCode,401);
  await app.close();
 }finally{await db.dropDatabase();await client.close();}
});
