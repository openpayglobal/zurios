import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";

test("MongoDB-backed auth, invitation lifecycle and tenant isolation", { skip: !process.env.MONGODB_URI }, async (t) => {
  process.env.NODE_ENV = "test";
  process.env.PLATFORM_BOOTSTRAP_TOKEN = "mebumip-integration-bootstrap-token-2026";
  process.env.MFA_ENCRYPTION_KEY = "b".repeat(64);
  process.env.AUDIT_SIGNING_KEY = "mebumip-integration-audit-signing-key";

  const [{ default: Fastify }, { MongoClient, ObjectId }, { ensureMeBuMIPIndexes }, { registerAuthRoutes }, { registerTenantMemberRoutes }, { registerAdminRoutes }, { registerDatabaseRateLimit }, { generateTotpCode }, { appendAuditEvent, verifyAuditEvent }, { getTestMailOutbox, clearTestMailOutbox }] = await Promise.all([
    import("fastify"), import("mongodb"), import("./database.js"), import("./auth.js"),
    import("./tenant-members.js"), import("./admin.js"), import("./rate-limit.js"), import("./mfa.js"), import("./security.js"), import("./mail.js"),
  ]);
  const client = new MongoClient(process.env.MONGODB_URI!);
  await client.connect();
  const db = client.db("mebumip_integration_" + randomUUID().replaceAll("-", ""));
  await ensureMeBuMIPIndexes(db);
  const app = Fastify({ logger: false });
  registerDatabaseRateLimit(app, db);
  registerAuthRoutes(app, db);
  registerTenantMemberRoutes(app, db);
  registerAdminRoutes(app, db);
  await app.ready();
  t.after(async () => { await app.close(); await db.dropDatabase(); await client.close(); });

  const bootstrap = await app.inject({ method: "POST", url: "/v1/platform/bootstrap", payload: {
    bootstrapToken: process.env.PLATFORM_BOOTSTRAP_TOKEN, email: "owner@example.test",
    password: "Integration-Owner-Password-2026!", displayName: "Integration Owner",
    companyName: "Blockchain Innovations LTD", tenantSlug: "blockchain-innovations",
  } });
  assert.equal(bootstrap.statusCode, 201);
  const tenant = await db.collection("tenants").findOne({ slug: "blockchain-innovations" });
  assert.ok(tenant);

  const login = await app.inject({ method: "POST", url: "/v1/auth/login", payload: { email: "owner@example.test", password: "Integration-Owner-Password-2026!" } });
  assert.equal(login.statusCode, 200);
  const token = login.json().accessToken as string;
  const setCookies = login.headers["set-cookie"];
  assert.ok(setCookies);
  const cookieParts = (Array.isArray(setCookies) ? setCookies : [setCookies]).map((value) => value.split(";")[0]!).filter((value) => value.startsWith("mebumip_session=") || value.startsWith("mebumip_csrf="));
  const cookieHeader = cookieParts.join("; ");
  const csrfCookie = cookieParts.find((value) => value.startsWith("mebumip_csrf="))?.split("=").slice(1).join("=");
  assert.ok(csrfCookie);
  const cookieMe = await app.inject({ method: "GET", url: "/v1/auth/me", headers: { cookie: cookieHeader } });
  assert.equal(cookieMe.statusCode, 200);
  const cookieCsrfDenied = await app.inject({ method: "POST", url: "/v1/auth/step-up", headers: { cookie: cookieHeader }, payload: { code: "000000" } });
  assert.equal(cookieCsrfDenied.statusCode, 401);
  const cookieCsrfAllowed = await app.inject({ method: "POST", url: "/v1/auth/step-up", headers: { cookie: cookieHeader, "x-csrf-token": decodeURIComponent(csrfCookie) }, payload: { code: "000000" } });
  assert.notEqual(cookieCsrfAllowed.statusCode, 401);
  const headers = { authorization: "Bearer " + token };
  const me = await app.inject({ method: "GET", url: "/v1/auth/me", headers });
  assert.equal(me.statusCode, 200);
  assert.equal(me.json().tenantMemberships[0].tenantId, String(tenant._id));
  const sessions = await app.inject({ method: "GET", url: "/v1/auth/sessions", headers });
  assert.equal(sessions.statusCode, 200);
  assert.equal(sessions.json().items.length, 1);
  assert.ok(String(sessions.json().items[0].userAgent).length > 0);
  const runtimeSettings = await app.inject({ method: "GET", url: "/v1/mac/settings", headers });
  assert.equal(runtimeSettings.statusCode, 200);
  assert.equal(runtimeSettings.json().settings.auditSigningConfigured, true);

  const setup = await app.inject({ method: "POST", url: "/v1/auth/mfa/setup", headers, payload: { currentPassword: "Integration-Owner-Password-2026!" } });
  assert.equal(setup.statusCode, 200);
  const enabled = await app.inject({ method: "POST", url: "/v1/auth/mfa/enable", headers, payload: { code: generateTotpCode(setup.json().secret) } });
  assert.equal(enabled.statusCode, 200);
  const cookieStepUp = await app.inject({ method: "POST", url: "/v1/auth/step-up", headers: { cookie: cookieHeader, "x-csrf-token": decodeURIComponent(csrfCookie) }, payload: { code: generateTotpCode(setup.json().secret) } });
  assert.equal(cookieStepUp.statusCode, 200);
  const macMembers = await app.inject({ method: "GET", url: "/v1/mac/tenants/" + String(tenant._id) + "/members", headers });
  assert.equal(macMembers.statusCode, 200);
  const protectedTenantOwner = await app.inject({ method: "PATCH", url: "/v1/mac/tenants/" + String(tenant._id) + "/members/" + bootstrap.json().userId, headers, payload: { role: "viewer" } });
  assert.equal(protectedTenantOwner.statusCode, 404);
  assert.ok(macMembers.json().members.some((member: { role: string }) => member.role === "tenant_owner"));
  clearTestMailOutbox();
  const macTenantInvite = await app.inject({ method: "POST", url: "/v1/mac/tenants/" + String(tenant._id) + "/invitations", headers, payload: { email: "mac-invite@example.test", role: "publisher" } });
  assert.equal(macTenantInvite.statusCode, 201);
  assert.equal("token" in macTenantInvite.json(), false);
  const macTenantInviteRevoke = await app.inject({ method: "DELETE", url: "/v1/mac/tenants/" + String(tenant._id) + "/invitations/" + macTenantInvite.json().invitationId, headers });
  assert.equal(macTenantInviteRevoke.statusCode, 204);
  const recoveryCode = enabled.json().recoveryCodes[0] as string;
  const stepUp = await app.inject({ method: "POST", url: "/v1/auth/step-up", headers, payload: { recoveryCode } });
  assert.equal(stepUp.statusCode, 200);
  const replay = await app.inject({ method: "POST", url: "/v1/auth/step-up", headers, payload: { recoveryCode } });
  assert.equal(replay.statusCode, 403);

  clearTestMailOutbox();
  clearTestMailOutbox();
  const platformInvitation = await app.inject({ method: "POST", url: "/v1/mac/admin-invitations", headers, payload: { email: "platform-admin@example.test", role: "platform_auditor" } });
  assert.equal(platformInvitation.statusCode, 201);
  assert.equal("token" in platformInvitation.json(), false);
  const platformInviteEmail = getTestMailOutbox().at(-1);
  assert.ok(platformInviteEmail);
  const platformInviteToken = platformInviteEmail.text.match(/Invitation token: ([A-Za-z0-9_-]+)/)?.[1];
  assert.ok(platformInviteToken);
  const platformAdminRegistration = await app.inject({ method: "POST", url: "/v1/auth/register-platform-admin", payload: { token: platformInviteToken, email: "platform-admin@example.test", password: "Integration-Platform-Admin-Password-2026!", displayName: "Platform Auditor" } });
  assert.equal(platformAdminRegistration.statusCode, 201);
  const createdPlatformAdmin = await db.collection("users").findOne({ normalizedEmail: "platform-admin@example.test" });
  assert.equal(createdPlatformAdmin?.platformRole, "platform_auditor");
  const protectedPlatformOwner = await app.inject({ method: "PATCH", url: "/v1/mac/admins/" + bootstrap.json().userId, headers, payload: { role: "platform_admin" } });
  assert.equal(protectedPlatformOwner.statusCode, 404);
  const duplicateAdminRegistration = await app.inject({ method: "POST", url: "/v1/auth/register-platform-admin", payload: { token: platformInviteToken, email: "platform-admin@example.test", password: "Integration-Platform-Admin-Password-2026!", displayName: "Platform Auditor" } });
  assert.equal(duplicateAdminRegistration.statusCode, 404);

  clearTestMailOutbox();
  const invitation = await app.inject({ method: "POST", url: "/v1/tenants/" + String(tenant._id) + "/invitations", headers, payload: { email: "member@example.test", role: "viewer" } });
  assert.equal(invitation.statusCode, 201);
  assert.equal("invitationToken" in invitation.json(), false);
  const invitationEmail = getTestMailOutbox().at(-1);
  assert.ok(invitationEmail);
  const invitationToken = invitationEmail.text.match(/Invitation token: ([A-Za-z0-9_-]+)/)?.[1];
  assert.ok(invitationToken);
  const registered = await app.inject({ method: "POST", url: "/v1/auth/register", payload: { token: invitationToken, email: "member@example.test", password: "Integration-Member-Password-2026!", displayName: "Invited Member" } });
  assert.equal(registered.statusCode, 201);
  const macMembershipUpdate = await app.inject({ method: "PATCH", url: "/v1/mac/tenants/" + String(tenant._id) + "/members/" + registered.json().userId, headers, payload: { role: "publisher" } });
  assert.equal(macMembershipUpdate.statusCode, 200);
  const replayInvite = await app.inject({ method: "POST", url: "/v1/auth/register", payload: { token: invitationToken, email: "member@example.test", password: "Integration-Member-Password-2026!", displayName: "Invited Member" } });
  assert.equal(replayInvite.statusCode, 404);
  clearTestMailOutbox();
  const existingUserAdminInvite = await app.inject({ method: "POST", url: "/v1/mac/admin-invitations", headers, payload: { email: "member@example.test", role: "platform_operator" } });
  assert.equal(existingUserAdminInvite.statusCode, 201);
  const existingInviteToken = getTestMailOutbox().at(-1)?.text.match(/Invitation token: ([A-Za-z0-9_-]+)/)?.[1];
  assert.ok(existingInviteToken);
  const memberLogin = await app.inject({ method: "POST", url: "/v1/auth/login", payload: { email: "member@example.test", password: "Integration-Member-Password-2026!" } });
  assert.equal(memberLogin.statusCode, 200);
  const existingAdminAccept = await app.inject({ method: "POST", url: "/v1/mac/admin-invitations/accept", headers: { authorization: "Bearer " + memberLogin.json().accessToken }, payload: { token: existingInviteToken } });
  assert.equal(existingAdminAccept.statusCode, 200);
  assert.equal(existingAdminAccept.json().role, "platform_operator");
  const platformAdminId = String(registered.json().userId);
  const roleUpdate = await app.inject({ method: "PATCH", url: "/v1/mac/admins/" + platformAdminId, headers, payload: { role: "platform_auditor" } });
  assert.equal(roleUpdate.statusCode, 200);
  assert.equal(roleUpdate.json().role, "platform_auditor");
  const suspendedAdmin = await app.inject({ method: "PATCH", url: "/v1/mac/admins/" + platformAdminId, headers, payload: { status: "suspended" } });
  assert.equal(suspendedAdmin.statusCode, 200);
  const revokedAdminSession = await app.inject({ method: "GET", url: "/v1/mad/overview", headers: { authorization: "Bearer " + memberLogin.json().accessToken } });
  assert.equal(revokedAdminSession.statusCode, 401);
  const reactivatedAdmin = await app.inject({ method: "PATCH", url: "/v1/mac/admins/" + platformAdminId, headers, payload: { status: "active" } });
  assert.equal(reactivatedAdmin.statusCode, 200);
  const reactivatedLogin = await app.inject({ method: "POST", url: "/v1/auth/login", payload: { email: "member@example.test", password: "Integration-Member-Password-2026!" } });
  assert.equal(reactivatedLogin.statusCode, 200);
  const auditorHeaders = { authorization: "Bearer " + reactivatedLogin.json().accessToken };
  const auditorMetrics = await app.inject({ method: "GET", url: "/v1/mad/overview", headers: auditorHeaders });
  assert.equal(auditorMetrics.statusCode, 200);
  const auditorAuditRead = await app.inject({ method: "GET", url: "/v1/mac/audit-events", headers: auditorHeaders });
  assert.equal(auditorAuditRead.statusCode, 200);
  const auditorAdminMutation = await app.inject({ method: "PATCH", url: "/v1/mac/admins/" + platformAdminId, headers: auditorHeaders, payload: { role: "platform_operator" } });
  assert.equal(auditorAdminMutation.statusCode, 403);
  const cancellableInvite = await app.inject({ method: "POST", url: "/v1/mac/admin-invitations", headers, payload: { email: "cancelled-admin@example.test", role: "platform_auditor" } });
  assert.equal(cancellableInvite.statusCode, 201);
  const revokeAdminInvite = await app.inject({ method: "DELETE", url: "/v1/mac/admin-invitations/" + cancellableInvite.json().invitationId, headers });
  assert.equal(revokeAdminInvite.statusCode, 204);

  const recoveryRequest = await app.inject({ method: "POST", url: "/v1/auth/password/recovery", payload: { email: "member@example.test" } });
  assert.equal(recoveryRequest.statusCode, 202);
  const recoveryEmail = getTestMailOutbox().at(-1);
  assert.ok(recoveryEmail);
  const resetToken = recoveryEmail.text.match(/Password reset token: ([A-Za-z0-9_-]+)/)?.[1];
  assert.ok(resetToken);
  const passwordReset = await app.inject({ method: "POST", url: "/v1/auth/password/reset", payload: { token: resetToken, newPassword: "Recovered-Member-Password-2026!" } });
  assert.equal(passwordReset.statusCode, 200);
  const resetReplay = await app.inject({ method: "POST", url: "/v1/auth/password/reset", payload: { token: resetToken, newPassword: "Recovered-Member-Password-2026!" } });
  assert.equal(resetReplay.statusCode, 400);
  const recoveredLogin = await app.inject({ method: "POST", url: "/v1/auth/login", payload: { email: "member@example.test", password: "Recovered-Member-Password-2026!" } });
  assert.equal(recoveredLogin.statusCode, 200);

  const foreignTenant = await db.collection("tenants").insertOne({ name: "Foreign Tenant", slug: "foreign-tenant", status: "active", createdAt: new Date() });
  const isolation = await app.inject({ method: "GET", url: "/v1/tenants/" + String(foreignTenant.insertedId) + "/members", headers });
  assert.equal(isolation.statusCode, 403);

  const auditEvents = await db.collection("auditEvents").find({}).toArray();
  assert.ok(auditEvents.length >= 4);
  assert.ok(auditEvents.every((event) => verifyAuditEvent(event as Record<string, unknown>)));
  assert.ok(auditEvents.every((event) => Number.isSafeInteger(event.sequence)));
  const auditVerification = await app.inject({ method: "GET", url: "/v1/mac/audit-events/verify", headers });
  assert.equal(auditVerification.statusCode, 200);
  assert.equal(auditVerification.json().invalid, 0);
  assert.equal(auditVerification.json().sequenceGaps, 0);
  const auditExport = await app.inject({ method: "GET", url: "/v1/mac/audit-events/export?limit=100", headers });
  assert.equal(auditExport.statusCode, 200);
  assert.equal(auditExport.json().integrity.unsignedOrInvalid, 0);
  assert.equal(auditExport.json().manifest.integrity.algorithm, "HMAC-SHA256");
  assert.equal(String(auditExport.json().manifest.integrity.signature).length, 64);
  const exportPageOne = await app.inject({ method: "GET", url: "/v1/mac/audit-events/export?limit=1", headers });
  assert.equal(exportPageOne.statusCode, 200);
  const exportCursor = exportPageOne.json().nextCursor as string;
  assert.ok(exportCursor);
  const exportPageTwo = await app.inject({ method: "GET", url: "/v1/mac/audit-events/export?limit=1&before=" + exportCursor, headers });
  assert.equal(exportPageTwo.statusCode, 200);
  assert.notEqual(String(exportPageOne.json().events[0]._id), String(exportPageTwo.json().events[0]._id));
  const firstSequence = await appendAuditEvent(db, { actorUserId: "integration", action: "test.audit.sequence.first", targetType: "test", outcome: "success", correlationId: randomUUID() });
  await appendAuditEvent(db, { actorUserId: "integration", action: "test.audit.sequence.second", targetType: "test", outcome: "success", correlationId: randomUUID() });
  await db.collection("auditEvents").deleteOne({ sequence: firstSequence.sequence });
  const gapCheck = await app.inject({ method: "GET", url: "/v1/mac/audit-events/verify", headers });
  assert.equal(gapCheck.statusCode, 200);
  assert.ok(gapCheck.json().sequenceGaps >= 1);
  assert.equal(await db.collection("tenantInvitations").countDocuments({ acceptedAt: { $exists: false }, revokedAt: { $exists: false } }), 0);
});
